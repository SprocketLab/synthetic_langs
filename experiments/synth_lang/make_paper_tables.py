#!/usr/bin/env python3
"""LaTeX tables for the paper (booktabs, layouts use the \\m{} macro).

  components      Table 1: SL2 (20k x 15) and sl-eng (100k x 3), window 20: PPL, type KL,
                  within-grammar KL, within-non-grammar KL, per-sentence recall
  components_20k  appendix: the same columns for sl-eng at 20k x 15
  tasks           Sec. 3: MKAR, MQAR and decode-recall accuracy next to BabyLM PPL

Medians over seeds at the epoch with the lowest validation PPL (KL and recall at the nearest
evaluation). Best value per column in bold.

    python make_paper_tables.py [components components_20k tasks]   # -> figures/table_<name>.tex
"""
import os, sys, json, glob
import numpy as np
import plot_paper_figs as F
import paper_style as P

SYN, OUT = F.SYN, F.OUT
ORDER = ["pure_tf", "4s4t_alternate", "4s4t_tf_first", "4s4t_ssm_first", "6s2t_start", "6s2t_end", "6s2t_even",
         "7s1t_mid", "pure_ssm", "pure_dp", "4d4t_alternate", "6d2t_start", "dsts_alternate"]


def cell(v, fmt, best):
    if v is None:
        return "--"
    s = format(v, fmt)
    return f"\\textbf{{{s}}}" if best else s


def column_best(vals, lower, fmt):
    """Best value as printed, so ties after rounding are all bold."""
    ok = [float(format(v, fmt)) for v in vals if v is not None]
    if not ok:
        return None
    return min(ok) if lower else max(ok)


def is_best(v, fmt, best):
    return v is not None and float(format(v, fmt)) == best


def write(name, lines):
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, f"table_{name}.tex")
    open(path, "w").write("\n".join(lines) + "\n")
    print("saved", os.path.normpath(path))


# Section 5.1: per-component results

COMPONENTS_CAPTION = {
    "components": "Results by language component with a window of 20: validation perplexity, the KL divergence "
                  "of the next-word type and within grammar and non-grammar words, and per-sentence recall accuracy "
                  "(Bayes ceiling 0.95 on \\sl, 1.0 on \\sleng). \\sl\\ uses 20k training sentences for 15 epochs and "
                  "\\sleng\\ 100k for 3 epochs, the same number of training tokens; medians over five seeds at the "
                  "epoch with the lowest validation perplexity.",
    "components_20k": "Results on \\sleng\\ with 20k training sentences for 15 epochs (the \\sl\\ setting), window 20; "
                      "columns as in Table~\\ref{tab:components}. Medians over five seeds at the epoch with the lowest "
                      "validation perplexity.",
}


def components(name="components"):
    """components: SL2 and sl-eng at the SL2 token budget (Table 1); components_20k: sl-eng at 20k x 15."""
    langs = {"components": [("\\sl", "lang_sl2_w20", ".2f"), ("\\sleng", "lang_sl2_sweep/sl-eng-d04_w20_n100k_ep3", ".1f")],
             "components_20k": [("\\sleng, 20k $\\times$ 15", "lang_sl2_sweep/sl-eng-d04_w20", ".1f")]}[name]
    # (header, value(run), format, lower is better)
    metrics = [("PPL", lambda r: min(r["val_ppls"]), None, True),
               ("Type", lambda r: F.at_best(r, "kl_divs", "kl_type"), ".3f", True),
               ("$\\gV_G$", lambda r: F.at_best(r, "kl_divs", "kl_within_grammar"), ".3f", True),
               ("$\\gV_N$", lambda r: F.at_best(r, "kl_divs", "kl_within_non_grammar"), ".3f", True),
               ("$\\gV_F$", lambda r: F.at_best(r, "recall_accs", "accuracy_sent"), ".2f", False)]
    table = {}   # (lang, metric) -> {cfg: median}
    for _, d, ppl_fmt in langs:
        for h, f, fmt, _ in metrics:
            table[(d, h)] = {c: (float(np.median([f(r) for r in F.runs(d, c)])) if F.runs(d, c) else None)
                             for c in ORDER}
    best = {(d, h): column_best(list(table[(d, h)].values()), lower, fmt or ppl_fmt)
            for _, d, ppl_fmt in langs for h, _, fmt, lower in metrics}

    ncol = len(metrics)
    env = "table*" if len(langs) > 1 else "table"
    lines = ["% generated by experiments/synth_lang/make_paper_tables.py; needs \\usepackage{booktabs}",
             f"\\begin{{{env}}}[t]", "\\centering", "\\small",
             "\\begin{tabular}{l" + "@{\\hspace{1.2em}}".join("r" * ncol for _ in langs) + "}", "\\toprule",
             " & " + " & ".join(f"\\multicolumn{{{ncol}}}{{c}}{{{n}}}" for n, _, _ in langs) + " \\\\",
             "".join(f"\\cmidrule(lr){{{2 + k * ncol}-{1 + (k + 1) * ncol}}}" for k in range(len(langs))),
             "Layers & " + " & ".join(h for _ in langs for h, *_ in metrics) + " \\\\", "\\midrule"]
    for c in ORDER:
        cells = []
        for _, d, ppl_fmt in langs:
            for h, _, fmt, _ in metrics:
                v = table[(d, h)][c]
                cells.append(cell(v, fmt or ppl_fmt, is_best(v, fmt or ppl_fmt, best[(d, h)])))
        lines.append(f"\\m{{{P.LAYOUT[c]}}} & " + " & ".join(cells) + " \\\\")
        if c in ("pure_ssm",):
            lines.append("\\midrule")
    lines += ["\\bottomrule", "\\end{tabular}", f"\\caption{{{COMPONENTS_CAPTION[name]}}}",
              "\\label{tab:" + name.replace("_", "") + "}", f"\\end{{{env}}}"]
    write(name, lines)


# Section 3: synthetic tasks vs BabyLM

def tasks():
    cfgs = ["pure_tf", "4s4t_alternate", "6s2t_start", "6s2t_even", "7s1t_mid", "pure_ssm"]

    def acc(pattern):
        fs = glob.glob(os.path.join(SYN, pattern, "*.json"))
        return float(np.median([json.load(open(f))["mean_acc"] for f in fs])) if fs else None

    cols = [("MKAR", lambda c: acc(f"mkar_d256_full/d256/{c}"), ".2f", False),
            ("MQAR", lambda c: acc(f"mqar_d256_full/d256/{c}"), ".2f", False),
            ("Decode-recall", lambda c: acc(f"d256/{c}"), ".2f", False),
            ("BabyLM PPL", lambda c: float(np.median([json.load(open(f))["best_ppl"] for f in
                                                      glob.glob(os.path.join(SYN, "prepretrain", "none", c, "*.json"))])),
             ".2f", True)]
    vals = {h: {c: f(c) for c in cfgs} for h, f, _, _ in cols}
    best = {h: column_best(list(vals[h].values()), lower, fmt) for h, _, fmt, lower in cols}
    lines = ["% generated by experiments/synth_lang/make_paper_tables.py; needs \\usepackage{booktabs}",
             "\\begin{table}[t]", "\\centering", "\\small",
             f"\\begin{{tabular}}{{l{'r' * len(cols)}}}", "\\toprule",
             "Layers & " + " & ".join(h for h, *_ in cols) + " \\\\", "\\midrule"]
    for c in cfgs:
        lines.append(f"\\m{{{P.LAYOUT[c]}}} & " + " & ".join(
            cell(vals[h][c], fmt, is_best(vals[h][c], fmt, best[h])) for h, _, fmt, _ in cols) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}",
              "\\caption{Accuracy on three synthetic tasks and perplexity on BabyLM, window 20, hidden size 256; "
              "medians over seeds.}", "\\label{tab:synthtasks}", "\\end{table}"]
    write("tasks", lines)


if __name__ == "__main__":
    for name in sys.argv[1:] or ["components", "components_20k", "tasks"]:
        components(name) if name.startswith("components") else globals()[name]()
